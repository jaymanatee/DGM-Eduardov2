"""Products for the synthetic tool-use trajectories, each with the materials it is made of.

The phase 1 generator has only six products, and four of them are in the phase 2 benchmark
(the battery, the fan, the pump and the motor). Trained on them, the benchmark would no longer
say whether the model handles products it has never seen. So this is a new catalogue, and no
product here shares a heading (4 digits) with a product of ``tool_use/bench/cases.jsonl``; a
test checks it. Materials may share codes with the benchmark: a bearing is a bearing.

Names come in Spanish and English because the questions are asked in both. HS codes follow
the 2022 nomenclature, as the UK Trade Tariff does. The rules themselves are not here: they
are downloaded once from the API (``tool_use/sft/fetch.py``) and read from disk afterwards.
"""

from __future__ import annotations

from dataclasses import dataclass, field

# Headings of the benchmark products: kept out of the training products.
BENCH_HEADINGS = frozenset({"6109", "8413", "8414", "8507", "8708", "9403"})


@dataclass(frozen=True)
class Material:
    es: str
    en: str
    code: str  # HS subheading, 6 digits


# Where the rule of an agreement has several subdivisions, the one that fits the product and
# why, in a few words for the reasoning; None leaves that agreement out for this product (the
# answer is not clear: overlapping sets, sets without a description, quotas that concern
# exports from Canada into the UK). A test checks that every such rule is annotated.
Subdivisions = dict[str, "tuple[int, str] | None"]


@dataclass(frozen=True)
class Product:
    es: str
    en: str
    code: str
    exw_range: tuple[int, int]  # euros
    materials: tuple[Material, ...]
    subdivisions: Subdivisions = field(default_factory=dict)


def _p(
    es: str,
    en: str,
    code: str,
    exw: tuple[int, int],
    *materials: tuple[str, str, str],
    subdivisions: Subdivisions | None = None,
) -> Product:
    return Product(es, en, code, exw, tuple(Material(*m) for m in materials), subdivisions or {})


